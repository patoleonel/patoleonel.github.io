function createNodeElement(item, type) {
    const div = document.createElement('div');
    div.className = `milestone-node ${type}-node`;
    div.setAttribute('data-id', item.id);
    div.setAttribute('data-type', type);
    if (item.connections) {
        div.setAttribute('data-connections', JSON.stringify(item.connections));
    }

    const titleEn = item.title_en || '';
    const titleEs = item.title_es || '';
    const isQuantum = titleEn.toLowerCase().includes('quantum') || titleEs.toLowerCase().includes('quantum') || titleEn.toLowerCase().includes('qiskit');
    const isSistemas = titleEn.toLowerCase().includes('utn') || titleEs.toLowerCase().includes('utn');

    let quantumGallery = '';
    if (isQuantum) {
        quantumGallery = `
            <div class="quantum-inline-gallery">
                <img src="images/certificado quantum JAM.webp" alt="Quantum Jam">
                <img src="images/image1quantum.webp" alt="Quantum 1">
                <img src="images/image2quantum.webp" alt="Quantum 2">
                <img src="images/image3quantum.webp" alt="Quantum 3">
                <img src="images/image4quantum.webp" alt="Quantum 4">
            </div>
        `;
    } else if (isSistemas) {
        quantumGallery = `
            <div class="single-inline-gallery">
                <img src="images/IngresoUTN.webp" alt="Ingreso UTN">
            </div>
        `;
    }

    if (type === 'takeaway') {
        const fullDesc = item['description_' + currentLang];
        const splitIdx = fullDesc.indexOf(':');
        if (splitIdx > -1) {
            const title = fullDesc.substring(0, splitIdx);
            const desc = fullDesc.substring(splitIdx + 1).trim();
            div.innerHTML = `
                <h3 class="node-title">${title}</h3>
                <p class="node-desc">${desc}</p>
            `;
        } else {
            div.innerHTML = `
                <h3 class="node-title">${fullDesc}</h3>
            `;
        }
    } else {
        div.innerHTML = `
            <span class="node-year">${item.year}</span>
            <h3 class="node-title">${item['title_' + currentLang]}</h3>
            <p class="node-desc">${item['description_' + currentLang]}</p>
            ${quantumGallery}
        `;
    }

    return div;
}

function renderTimeline() {
    connectionObserver.disconnect();
    const grid = document.getElementById('timeline-grid-nodes');
    grid.innerHTML = '';

    domNodes.academic = {};
    domNodes.professional = {};
    domNodes.takeaways = {};

    const maxLen = Math.max(
        portfolioData.academicMilestones.length,
        portfolioData.professionalMilestones.length,
        portfolioData.keyTakeaways.length
    );

    for (let i = 0; i < maxLen; i++) {
        // 1. Academic
        if (portfolioData.academicMilestones[i]) {
            const acadItem = portfolioData.academicMilestones[i];
            const acadNode = createNodeElement(acadItem, 'academic');
            grid.appendChild(acadNode);
            domNodes.academic[acadItem.id] = { elem: acadNode, data: acadItem };
            connectionObserver.observe(acadNode);
        } else {
            grid.appendChild(document.createElement('div'));
        }

        // 2. Takeaway
        if (portfolioData.keyTakeaways[i]) {
            const takeItem = portfolioData.keyTakeaways[i];
            const takeNode = createNodeElement(takeItem, 'takeaway');
            grid.appendChild(takeNode);
            domNodes.takeaways[takeItem.id] = { elem: takeNode, data: takeItem };
            connectionObserver.observe(takeNode);
        } else {
            grid.appendChild(document.createElement('div'));
        }

        // 3. Professional
        if (portfolioData.professionalMilestones[i]) {
            const profItem = portfolioData.professionalMilestones[i];
            const profNode = createNodeElement(profItem, 'professional');
            grid.appendChild(profNode);
            domNodes.professional[profItem.id] = { elem: profNode, data: profItem };
            connectionObserver.observe(profNode);
        } else {
            grid.appendChild(document.createElement('div'));
        }
    }
}

function drawConnections() {
    const svg = document.getElementById('spiderweb-canvas');
    svg.innerHTML = ''; // clear existing lines

    const svgRect = svg.getBoundingClientRect();

    // Helper to get relative coordinates
    const getCoords = (elem) => {
        const rect = elem.getBoundingClientRect();
        return {
            x: rect.left + rect.width / 2 - svgRect.left,
            y: rect.top + rect.height / 2 - svgRect.top,
            leftEdge: rect.left - svgRect.left,
            rightEdge: rect.right - svgRect.left,
            topEdge: rect.top - svgRect.top,
            bottomEdge: rect.bottom - svgRect.top
        };
    };

    // --- Vertical Time Lines ---
    // Academic vertical line
    const acadNodesList = Object.values(domNodes.academic);
    for (let i = 0; i < acadNodesList.length - 1; i++) {
        const start = getCoords(acadNodesList[i].elem);
        const end = getCoords(acadNodesList[i + 1].elem);
        createLine(svg, start, end, acadNodesList[i].data.id, acadNodesList[i + 1].data.id, true);
    }

    // Professional vertical line
    const profNodesList = Object.values(domNodes.professional);
    for (let i = 0; i < profNodesList.length - 1; i++) {
        const start = getCoords(profNodesList[i].elem);
        const end = getCoords(profNodesList[i + 1].elem);
        createLine(svg, start, end, profNodesList[i].data.id, profNodesList[i + 1].data.id, true);
    }

    // --- Horizontal/Diagonal Takeaway Lines ---
    // Draw lines for academic (Left to Center)
    Object.values(domNodes.academic).forEach(nodeObj => {
        const { elem, data } = nodeObj;
        const startCoords = getCoords(elem);

        // Start from the right edge of the academic node
        const start = { x: startCoords.rightEdge, y: startCoords.y };

        data.connections.forEach(targetId => {
            if (domNodes.takeaways[targetId]) {
                const endCoords = getCoords(domNodes.takeaways[targetId].elem);
                // End at the left edge of the takeaway node
                const end = { x: endCoords.leftEdge, y: endCoords.y };
                createLine(svg, start, end, data.id, targetId, false);
            }
        });
    });

    // Draw lines for professional (Right to Center)
    Object.values(domNodes.professional).forEach(nodeObj => {
        const { elem, data } = nodeObj;
        const startCoords = getCoords(elem);

        // Start from the left edge of the professional node
        const start = { x: startCoords.leftEdge, y: startCoords.y };

        data.connections.forEach(targetId => {
            if (domNodes.takeaways[targetId]) {
                const endCoords = getCoords(domNodes.takeaways[targetId].elem);
                // End at the right edge of the takeaway node
                const end = { x: endCoords.rightEdge, y: endCoords.y };
                createLine(svg, start, end, data.id, targetId, false);
            }
        });
    });
}

function createLine(svg, start, end, sourceId, targetId, isVertical = false) {
    const path = document.createElementNS('http://www.w3.org/2000/svg', 'path');

    let d;
    if (isVertical) {
        d = `M ${start.x} ${start.y} L ${end.x} ${end.y}`;
    } else {
        // Draw a nice curved path (bezier) instead of a straight line
        const dx = Math.abs(end.x - start.x);
        const controlPointX = start.x + (end.x > start.x ? dx / 2 : -dx / 2);
        d = `M ${start.x} ${start.y} C ${controlPointX} ${start.y}, ${controlPointX} ${end.y}, ${end.x} ${end.y}`;
    }

    path.setAttribute('d', d);
    path.classList.add('connection-line');
    if (isVertical) path.classList.add('time-line');

    path.setAttribute('data-source', sourceId);
    path.setAttribute('data-target', targetId);

    svg.appendChild(path);
}

